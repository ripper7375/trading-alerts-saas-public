/**
 * Server-safe mirror of `lib/context/locale-context.tsx`'s dictionary map, for
 * use in `generateMetadata()` and other Server Components that run before any
 * client provider exists. Deliberately a separate module (no `'use client'`,
 * no React) rather than importing from locale-context.tsx directly, so server
 * code never pulls client-context internals into its module graph.
 *
 * Unlike the client — which keeps only `en-GB` (plus the small `en-US`
 * overlay) in its bundle and fetches every other language as a chunk of its
 * own, see `lib/i18n/client-dictionaries.ts` — this loads every dictionary
 * eagerly, and metadata generation needs a synchronous, deterministic result.
 * Server Components write their text through `getServerTranslator()`
 * (`lib/i18n/server-translator.ts`), which reads from here.
 *
 * Server Components and pages share one chunk of this (19 dictionaries, 6.5 MB), so
 * for them the size does not matter. A ROUTE HANDLER must not import this file,
 * directly or through another module: Turbopack gave every group of route
 * handlers that reached it its own 7.8 MB copy plus a 7.7 MB source map (four
 * copies, 62 MB of `.next` on 2026-11-23), and a copy grows by about 0.8 MB with
 * every language that is added. `__tests__/lib/i18n/route-handlers-and-dictionaries.test.ts`
 * fails when a route handler reaches the dictionaries. A route handler that needs
 * a few keys reads a small generated file instead, as `lib/intake/server/reply.ts`
 * does (`lib/i18n/intake-refusal-messages.json`, generated by
 * `scripts/i18n/generate-intake-refusal-messages.cjs`) and as the world-gold
 * route does (`lib/i18n/world-gold-messages.json`).
 */
const dictionaries: Record<string, Record<string, string>> = {
  'en-GB': enGBDict,
  'en-US': enUSDict,
  th: thDict,
  de: deDict,
  es: esDict,
  ja: jaDict,
  hi: hiDict,
  vi: viDict,
  id: idDict,
  tr: trDict,
  ur: urDict,
  pt: ptDict,
  'pt-BR': ptBRDict,
  it: itDict,
  ar: arDict,
  fr: frDict,
  ko: koDict,
  zh: zhDict,
  'zh-TW': zhTWDict,
};

/** Same fallback convention as `dictionaryFor()` in locale-context.tsx: en-GB is the base. */
export function getDictionary(language: string): Record<string, string> {
  return dictionaries[language] || dictionaries['en-GB']!;
}
