#!/usr/bin/env node
/**
 * The static prompt texts of the reply path: sync, review sheet and approval
 * (build step 7, part 2; the pattern of scripts/intake/matrix_tool.py).
 *
 * `config/reply/prompts/system-rules.v1.txt` and `wording-guide.v1.txt` are the texts a person
 * reads and approves. The prompt assembler is plain TypeScript with no file access (lib/reply is
 * pure), so this tool writes the same two texts into `lib/reply/context/static-text.ts`, and
 * `check` fails when the two differ by one character.
 *
 * WHAT IT WRITES
 *   lib/reply/context/static-text.ts       the two texts as TypeScript (generated; do not edit)
 *   config/reply/prompts/review.md         the texts in full, with their sizes and SHA-256
 *   config/reply/prompts/approval.json     the sign-off. `record` writes it PENDING and NEVER
 *                                          writes APPROVED: a person edits status, approved_by
 *                                          and approved_on. It holds the SHA-256 of the texts as
 *                                          they were reviewed, so any later edit shows up as
 *                                          "changed after approval" and puts it back to PENDING.
 *
 * NO GENERATED FILE LISTS A STATUS, so signing approval.json makes nothing stale.
 *
 * USAGE (from the repository root)
 *   node scripts/reply/prompts-tool.js record
 *   node scripts/reply/prompts-tool.js check [--require-approved]
 * `--root DIR` points either command at another tree with the same layout (the tests do).
 *
 * Exit codes: 0 fine; 1 a difference, a stale approval or (with the gate) PENDING; 2 a file is
 * unusable. Node standard library only.
 */

'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const PROMPTS_VERSION = 'prompts.v1';
const APPROVAL_SCHEMA = 'prompts-approval/1';
const AREA = 'prompts';
const PENDING = 'PENDING';
const APPROVED = 'APPROVED';

const FILES = {
  rules: 'config/reply/prompts/system-rules.v1.txt',
  wording: 'config/reply/prompts/wording-guide.v1.txt',
  generated: 'lib/reply/context/static-text.ts',
  review: 'config/reply/prompts/review.md',
  approval: 'config/reply/prompts/approval.json',
};

class ToolError extends Error {}

const lf = (text) => text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');

function readText(root, rel) {
  const full = path.join(root, rel);
  if (!fs.existsSync(full)) throw new ToolError(`${rel} is missing`);
  return lf(fs.readFileSync(full, 'utf8'));
}

function sha256(text) {
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

/** The two texts, each with its trailing newline removed (the assembler adds the separators). */
function loadTexts(root) {
  const rules = readText(root, FILES.rules).replace(/\n+$/, '');
  const wording = readText(root, FILES.wording).replace(/\n+$/, '');
  for (const [name, text] of [
    ['system rules', rules],
    ['wording guide', wording],
  ]) {
    if (text.trim() === '') throw new ToolError(`${name}: the text is empty`);
    if (/^@@ /m.test(text)) {
      throw new ToolError(
        `${name}: a line starts with the marker prefix; only the assembler writes those`
      );
    }
    // eslint-disable-next-line no-control-regex
    if (/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/.test(text)) {
      throw new ToolError(`${name}: the text has a control character`);
    }
  }
  return { rules, wording };
}

/** The digest an approval refers to: the version and both texts. */
function contentSha256(texts) {
  return sha256(
    JSON.stringify({
      version: PROMPTS_VERSION,
      system_rules: texts.rules,
      wording_guide: texts.wording,
    })
  );
}

/** A string literal the way Prettier prints it with singleQuote: single unless that needs more escapes. */
function literal(value) {
  const singles = (value.match(/'/g) || []).length;
  const doubles = (value.match(/"/g) || []).length;
  const quote = singles > doubles ? '"' : "'";
  const body = value
    .replace(/\\/g, '\\\\')
    .replace(new RegExp(quote, 'g'), `\\${quote}`);
  return `${quote}${body}${quote}`;
}

function constant(name, text) {
  const lines = text.split('\n').map((line) => `  ${literal(line)},`);
  return `export const ${name} = [\n${lines.join('\n')}\n].join('\\n');\n`;
}

function renderGenerated(texts) {
  return (
    '/**\n' +
    ' * GENERATED by scripts/reply/prompts-tool.js from config/reply/prompts/*.v1.txt.\n' +
    ' * Do not edit: edit the .txt files and run `node scripts/reply/prompts-tool.js record`.\n' +
    ' * `check` (and a Jest test) fail when this file and the texts differ by one character.\n' +
    ' *\n' +
    ' * @module lib/reply/context/static-text\n' +
    ' */\n\n' +
    `export const PROMPTS_VERSION = '${PROMPTS_VERSION}';\n\n` +
    constant('SYSTEM_RULES_TEXT', texts.rules) +
    '\n' +
    constant('WORDING_GUIDE_TEXT', texts.wording)
  );
}

function stats(text) {
  return {
    chars: [...text].length,
    lines: text.split('\n').length,
    words: text.split(/\s+/).filter(Boolean).length,
  };
}

function renderReview(texts) {
  const fence = (text) => `\`\`\`text\n${text}\n\`\`\``;
  const rules = stats(texts.rules);
  const wording = stats(texts.wording);
  return (
    `# Static prompt ${PROMPTS_VERSION}: review sheet\n\n` +
    'Generated by `node scripts/reply/prompts-tool.js record`; do not edit. Read the two texts below, then sign ' +
    '`approval.json` (status, name, date). What you approve is these words: **what the model is told about its role, ' +
    'direction, numbers, untrusted text, output shape and wording, in the same text for every trader.**\n\n' +
    '## What to check\n\n' +
    "- **Direction is never the model's.** The text says the server copies it from the SYN line, and the output shapes have no direction key.\n" +
    '- **Numbers are ids.** The model writes `{Z1.invalidation}`, never a figure; the fixed ids it lists are the ones the OHLC block and the profile use.\n' +
    "- **The trader's words are data.** The question and the history are told to be ignored as instructions.\n" +
    '- **The limits equal the contracts** (`REPORT1_LIMITS`, `ANSWER_LIMITS`): a test holds the text to them.\n' +
    '- **The wording guide is architecture 5.9**, the Always and Never rows, in English. The 19 language phrase lists that enforce it are a separate area (part 4).\n' +
    '- **It is written once, in English, and is the same for every user and language**: it must stay that way so the cache can serve it.\n\n' +
    '## Sizes\n\n' +
    '| Text | Characters | Lines | Words |\n| --- | --- | --- | --- |\n' +
    `| System rules | ${rules.chars} | ${rules.lines} | ${rules.words} |\n` +
    `| Wording guide | ${wording.chars} | ${wording.lines} | ${wording.words} |\n\n` +
    `The two together are held under 1,500 estimated tokens by \`__tests__/lib/reply/context/static-text.test.ts\`.\n\n` +
    `## Fingerprint\n\n- version: \`${PROMPTS_VERSION}\`\n- system rules SHA-256: \`${sha256(texts.rules)}\`\n- wording guide SHA-256: \`${sha256(texts.wording)}\`\n- content SHA-256 (what the approval refers to): \`${contentSha256(texts)}\`\n\n` +
    `## System rules (\`${FILES.rules}\`)\n\n${fence(texts.rules)}\n\n` +
    `## Wording guide (\`${FILES.wording}\`)\n\n${fence(texts.wording)}\n`
  );
}

function newApproval(digest, old) {
  const keep =
    old !== null &&
    old.status === APPROVED &&
    old.content_sha256 === digest &&
    typeof old.approved_by === 'string' &&
    old.approved_by !== '' &&
    typeof old.approved_on === 'string' &&
    old.approved_on !== '';
  return keep
    ? old
    : {
        schema: APPROVAL_SCHEMA,
        area: AREA,
        status: PENDING,
        approved_by: '',
        approved_on: '',
        content_sha256: digest,
        note: '',
      };
}

function dumpApproval(approval) {
  return `${JSON.stringify(approval, null, 2)}\n`;
}

function readApproval(root) {
  const full = path.join(root, FILES.approval);
  if (!fs.existsSync(full)) return null;
  try {
    return JSON.parse(lf(fs.readFileSync(full, 'utf8')));
  } catch (error) {
    throw new ToolError(`${FILES.approval} is not JSON: ${error.message}`);
  }
}

const APPROVAL_KEYS = [
  'schema',
  'area',
  'status',
  'approved_by',
  'approved_on',
  'content_sha256',
  'note',
];

function approvalProblems(approval, digest) {
  const problems = [];
  if (
    approval === null ||
    typeof approval !== 'object' ||
    Array.isArray(approval)
  ) {
    return [`${FILES.approval} must be an object`];
  }
  for (const key of APPROVAL_KEYS) {
    if (!(key in approval)) problems.push(`${FILES.approval} lacks "${key}"`);
  }
  for (const key of Object.keys(approval)) {
    if (!APPROVAL_KEYS.includes(key))
      problems.push(`${FILES.approval} has an unknown key "${key}"`);
  }
  if (approval.schema !== APPROVAL_SCHEMA)
    problems.push(`schema must be ${APPROVAL_SCHEMA}`);
  if (approval.area !== AREA) problems.push(`area must be ${AREA}`);
  if (![PENDING, APPROVED].includes(approval.status)) {
    problems.push(`status must be ${PENDING} or ${APPROVED}`);
  }
  if (approval.status === APPROVED) {
    if (
      typeof approval.approved_by !== 'string' ||
      approval.approved_by.trim() === ''
    ) {
      problems.push('an APPROVED area needs approved_by');
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(approval.approved_on))) {
      problems.push('an APPROVED area needs approved_on as YYYY-MM-DD');
    }
  }
  if (approval.content_sha256 !== digest) {
    problems.push(
      'the approval was written for other texts: run `record`, then read and sign again'
    );
  }
  return problems;
}

/** Write the generated file, the review sheet and the approval (PENDING unless it is still valid). */
function record(root) {
  const texts = loadTexts(root);
  const digest = contentSha256(texts);
  let old = null;
  try {
    old = readApproval(root);
  } catch {
    old = null;
  }
  const writes = [
    [FILES.generated, renderGenerated(texts)],
    [FILES.review, renderReview(texts)],
    [FILES.approval, dumpApproval(newApproval(digest, old))],
  ];
  for (const [rel, text] of writes) {
    const full = path.join(root, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text, 'utf8');
  }
  return writes.map(([rel]) => rel);
}

/** Every difference between the texts and what is on disk; an empty list means all is as it should be. */
function check(root, { requireApproved = false } = {}) {
  const texts = loadTexts(root);
  const digest = contentSha256(texts);
  const problems = [];
  const compare = (rel, expected) => {
    let found;
    try {
      found = readText(root, rel);
    } catch (error) {
      problems.push(error.message);
      return;
    }
    if (found !== lf(expected)) {
      problems.push(`${rel} differs from a fresh run: run \`record\``);
    }
  };
  compare(FILES.generated, renderGenerated(texts));
  compare(FILES.review, renderReview(texts));
  let approval = null;
  try {
    approval = readApproval(root);
  } catch (error) {
    problems.push(error.message);
  }
  if (approval === null) {
    problems.push(`${FILES.approval} is missing`);
  } else {
    problems.push(...approvalProblems(approval, digest));
    if (requireApproved && approval.status !== APPROVED) {
      problems.push(
        'the static prompt is PENDING: it does not ship unapproved'
      );
    }
  }
  return { problems, status: approval === null ? null : approval.status };
}

function main(argv) {
  const args = argv.slice(2);
  const rootIndex = args.indexOf('--root');
  const root =
    rootIndex === -1
      ? path.resolve(__dirname, '..', '..')
      : path.resolve(args[rootIndex + 1]);
  const command = args.find(
    (arg, index) => !arg.startsWith('--') && args[index - 1] !== '--root'
  );
  try {
    if (command === 'record') {
      for (const rel of record(root)) console.log(`wrote ${rel}`);
      return 0;
    }
    if (command === 'check') {
      const { problems, status } = check(root, {
        requireApproved: args.includes('--require-approved'),
      });
      if (problems.length > 0) {
        for (const problem of problems) console.error(`- ${problem}`);
        return 1;
      }
      console.log(`the static prompt is as it should be (approval ${status})`);
      return 0;
    }
    console.error(
      'usage: prompts-tool.js record | check [--require-approved] [--root DIR]'
    );
    return 2;
  } catch (error) {
    if (error instanceof ToolError) {
      console.error(error.message);
      return 2;
    }
    throw error;
  }
}

module.exports = {
  FILES,
  PROMPTS_VERSION,
  check,
  contentSha256,
  loadTexts,
  record,
  renderGenerated,
};

if (require.main === module) {
  process.exitCode = main(process.argv);
}
